//! Compile-time checked translations from Rails-style YAML locale files.
//!
//! A codon is the three-letter unit through which DNA is *translated*; this
//! crate is the unit through which your app is. At build time it reads YAML
//! locale files (the format Rails uses: `cs.yml`, `de.yml`, …) and turns every
//! key into a typed Rust function. A missing translation, a typo in a key or a
//! wrong interpolation argument becomes a compile error instead of a
//! "translation missing" in production.
//!
//! # Setup
//!
//! ```toml
//! [dependencies]
//! codon = "0.1"
//!
//! [build-dependencies]
//! codon = { version = "0.1", features = ["build"] }
//! ```
//!
//! `build.rs`:
//!
//! ```no_run
//! fn main() -> Result<(), Box<dyn std::error::Error>> {
//! # #[cfg(feature = "build")]
//!     codon::Build::new()
//!         .locale("cs", "locales/cs.yml") // the first locale is the default
//!         .locale("de", "locales/de.yml")
//!         .url_prefix("de", "at") // German pages live under /at
//!         .generate()?;
//!     Ok(())
//! }
//! ```
//!
//! Anywhere in the crate (typically `src/i18n.rs`):
//!
//! ```ignore
//! codon::include!();
//! ```
//!
//! # What gets generated
//!
//! Given
//!
//! ```yaml
//! cs:
//!   nav:
//!     domu: "Domů"
//!   auth:
//!     new_intro: "Nastavte nové heslo pro účet %{email}."
//!     privacy_html: "Souhlasím se %{link}."
//!     items:
//!       one: "%{count} položka"
//!       few: "%{count} položky"
//!       other: "%{count} položek"
//!   steps:
//!     - "Vyberte"
//!     - "Objednejte"
//! ```
//!
//! the generated code contains (simplified)
//!
//! ```ignore
//! pub enum Locale { Cs, De }
//! pub mod t {
//!     pub mod nav {
//!         pub fn domu(locale: Locale) -> &'static str;
//!     }
//!     pub mod auth {
//!         pub fn new_intro(locale: Locale, email: impl Display) -> String;
//!         pub fn privacy(locale: Locale, link: impl codon::HtmlArg) -> codon::Html;
//!         pub fn items(locale: Locale, count: i64) -> String;
//!     }
//!     pub fn steps(locale: Locale) -> &'static [&'static str];
//! }
//! pub fn lookup(locale: Locale, key: &str) -> Option<&'static str>;
//! ```
//!
//! The [`Build`] documentation lists all the rules (plurals, `_html` keys,
//! missing keys, identifier escaping); the README has a complete example.
//!
//! # Runtime
//!
//! The runtime part is small and `no_std` (it only needs `alloc`), so the
//! generated code works on the server and in `wasm32-unknown-unknown`:
//!
//! - [`Html`], [`HtmlArg`] and [`Escaped`]: trusted HTML from `_html` keys and
//!   escaping of the values interpolated into it,
//! - [`plural`]: CLDR cardinal plural rules,
//! - [`path`]: locale prefixes in URLs (`/kontakt` ↔ `/at/kontakt`).
//!
//! # Features
//!
//! - `build`: the code generator (`Build`); enable it only in
//!   `[build-dependencies]`.
//! - `serde`: `Serialize`/`Deserialize` for the generated `Locale` (as its
//!   code, e.g. `"cs"`). Enable it on the runtime dependency.

#![cfg_attr(not(feature = "build"), no_std)]

extern crate alloc;

#[cfg(feature = "build")]
mod build;
mod html;
pub mod path;
pub mod plural;

#[cfg(feature = "build")]
pub use build::{Build, Error, Generated, Problem};
pub use html::{Escaped, Html, HtmlArg, escape_html};

/// The error returned when parsing a string into a generated `Locale` fails.
///
/// ```
/// let err = codon::UnknownLocale::new("fr");
/// assert_eq!(err.to_string(), "unknown locale `fr`");
/// assert_eq!(err.input(), "fr");
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct UnknownLocale {
    input: alloc::string::String,
}

impl UnknownLocale {
    /// Creates the error for the given input.
    pub fn new(input: impl Into<alloc::string::String>) -> Self {
        Self {
            input: input.into(),
        }
    }

    /// The string that is not a known locale.
    #[must_use]
    pub fn input(&self) -> &str {
        &self.input
    }
}

impl core::fmt::Display for UnknownLocale {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "unknown locale `{}`", self.input)
    }
}

impl core::error::Error for UnknownLocale {}

/// Includes the code generated by `Build::generate` (`$OUT_DIR/codon.rs`).
///
/// It expands to `include!(concat!(env!("OUT_DIR"), "/codon.rs"));` and can
/// be used in any module, not only the crate root.
///
/// ```ignore
/// mod i18n {
///     codon::include!();
/// }
/// use i18n::{Locale, t};
/// ```
#[macro_export]
macro_rules! include {
    () => {
        ::core::include!(::core::concat!(::core::env!("OUT_DIR"), "/codon.rs"));
    };
}

/// Implementation details used by the generated code. Not public API.
#[doc(hidden)]
pub mod __private {
    #[cfg(feature = "serde")]
    pub use serde;

    /// Implements `Serialize`/`Deserialize` for a generated `Locale` when the
    /// `serde` feature is on, and nothing otherwise.
    #[cfg(feature = "serde")]
    #[macro_export]
    #[doc(hidden)]
    macro_rules! __impl_serde {
        ($locale:ident) => {
            impl $crate::__private::serde::Serialize for $locale {
                fn serialize<S: $crate::__private::serde::Serializer>(
                    &self,
                    serializer: S,
                ) -> ::core::result::Result<S::Ok, S::Error> {
                    serializer.serialize_str(self.as_str())
                }
            }

            impl<'de> $crate::__private::serde::Deserialize<'de> for $locale {
                fn deserialize<D: $crate::__private::serde::Deserializer<'de>>(
                    deserializer: D,
                ) -> ::core::result::Result<Self, D::Error> {
                    struct Visitor;
                    impl $crate::__private::serde::de::Visitor<'_> for Visitor {
                        type Value = $locale;
                        fn expecting(
                            &self,
                            f: &mut ::core::fmt::Formatter<'_>,
                        ) -> ::core::fmt::Result {
                            f.write_str("a locale code")
                        }
                        fn visit_str<E: $crate::__private::serde::de::Error>(
                            self,
                            value: &str,
                        ) -> ::core::result::Result<$locale, E> {
                            value.parse().map_err(E::custom)
                        }
                    }
                    deserializer.deserialize_str(Visitor)
                }
            }
        };
    }

    /// Implements `Serialize`/`Deserialize` for a generated `Locale` when the
    /// `serde` feature is on, and nothing otherwise.
    #[cfg(not(feature = "serde"))]
    #[macro_export]
    #[doc(hidden)]
    macro_rules! __impl_serde {
        ($locale:ident) => {};
    }
}
