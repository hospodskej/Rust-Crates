//! Turning the model into Rust source.

use proc_macro2::{Ident, Literal, TokenStream};
use quote::{format_ident, quote};

use super::ident::Name;
use super::model::{self, Item, Kind, LocaleInfo, Model};
use super::parse::Value;
use super::template::{self, Segment};
use crate::plural::Category;

/// Lints that the generated code must not trigger in the consumer crate.
fn allow() -> TokenStream {
    quote! {
        #[allow(
            dead_code,
            unused_imports,
            unused_variables,
            non_snake_case,
            non_camel_case_types,
            missing_docs,
            unreachable_pub,
            clippy::all,
            clippy::pedantic,
            clippy::nursery
        )]
    }
}

pub(crate) fn generate(model: &Model) -> String {
    let locale = locale_enum(model);
    let root = tree(model);
    let module = module(
        model,
        &root,
        &model.module,
        &doc_lines(&["Translations.".to_owned()]),
    );
    let lookup = lookup(model);
    let tokens = quote! {
        #locale
        #module
        #lookup
    };
    let file: syn::File = syn::parse2(tokens)
        .unwrap_or_else(|e| panic!("codon generated invalid Rust ({e}); please report this bug"));
    let files: Vec<&str> = model.locales.iter().map(|l| l.file.as_str()).collect();
    format!(
        "// @generated by codon from {}. Do not edit.\n\n{}",
        files.join(", "),
        add_blank_lines(&prettyplease::unparse(&file))
    )
}

/// Separates items with blank lines, which prettyplease does not do.
fn add_blank_lines(code: &str) -> String {
    let mut out = String::with_capacity(code.len() + code.len() / 16);
    let mut previous = "";
    for line in code.lines() {
        let trimmed = line.trim_start();
        let item_start = ["///", "#[", "pub ", "impl ", "::codon::"]
            .iter()
            .any(|p| trimmed.starts_with(p));
        if item_start && (previous == "}" || previous.starts_with("use ")) {
            out.push('\n');
        }
        out.push_str(line);
        out.push('\n');
        previous = trimmed;
    }
    out
}

fn str_lit(s: &str) -> Literal {
    Literal::string(s)
}

fn doc_lines(lines: &[String]) -> TokenStream {
    lines
        .iter()
        .map(|line| {
            let text = if line.is_empty() {
                String::new()
            } else {
                format!(" {line}")
            };
            quote!(#[doc = #text])
        })
        .collect()
}

fn variant(locale: &LocaleInfo) -> Ident {
    format_ident!("{}", locale.variant)
}

fn locale_enum(model: &Model) -> TokenStream {
    let allow = allow();
    let default = &model.locales[0];
    let variants = model.locales.iter().enumerate().map(|(i, l)| {
        let v = variant(l);
        let doc = if i == 0 {
            format!(" `{}` (the default locale)", l.code)
        } else {
            format!(" `{}`", l.code)
        };
        let default_attr = (i == 0).then(|| quote!(#[default]));
        quote! {
            #[doc = #doc]
            #default_attr
            #v
        }
    });
    let all: Vec<Ident> = model.locales.iter().map(variant).collect();
    let count = Literal::usize_unsuffixed(all.len());
    let default_variant = variant(default);
    let codes = model.locales.iter().map(|l| str_lit(&l.code));
    let codes2 = codes.clone();
    let url_prefixes = model.locales.iter().map(|l| {
        l.prefix.as_ref().map_or_else(
            || quote!(None),
            |p| {
                let p = str_lit(p);
                quote!(Some(#p))
            },
        )
    });
    let prefixed: Vec<(Ident, Literal)> = model
        .locales
        .iter()
        .filter_map(|l| l.prefix.as_ref().map(|p| (variant(l), str_lit(p))))
        .collect();
    let path_entries = prefixed.iter().map(|(v, p)| quote!((Self::#v, #p)));
    let from_prefix_arms = prefixed.iter().map(|(v, p)| quote!(#p => Some(Self::#v),));
    let rules = model.locales.iter().map(|l| {
        let rule = format_ident!("{}", format!("{:?}", l.rule));
        quote!(::codon::plural::PluralRule::#rule)
    });
    let paths_doc = " Locale prefixes in URL paths: `/kontakt` for the default locale, \
                     `/<prefix>/kontakt` for the others.";
    quote! {
        /// A locale with translations.
        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
        #allow
        pub enum Locale {
            #(#variants,)*
        }

        #allow
        impl Locale {
            /// Every locale, the default one first.
            pub const ALL: [Self; #count] = [#(Self::#all),*];

            /// The default locale, used for unprefixed URLs.
            pub const DEFAULT: Self = Self::#default_variant;

            #[doc = #paths_doc]
            pub const PATHS: ::codon::path::Prefixes<Self> =
                ::codon::path::Prefixes::from_static(&[#(#path_entries),*]);

            /// The locale code, as in the YAML file (`"cs"`).
            pub const fn as_str(self) -> &'static str {
                match self {
                    #(Self::#all => #codes,)*
                }
            }

            /// The URL prefix (`"at"` for `/at/…`), `None` for locales served
            /// at the root.
            pub const fn url_prefix(self) -> Option<&'static str> {
                match self {
                    #(Self::#all => #url_prefixes,)*
                }
            }

            /// The locale served under a URL prefix (without slashes).
            pub fn from_url_prefix(prefix: &str) -> Option<Self> {
                match prefix {
                    #(#from_prefix_arms)*
                    _ => None,
                }
            }

            /// The CLDR plural rule of the locale.
            pub const fn plural_rule(self) -> ::codon::plural::PluralRule {
                match self {
                    #(Self::#all => #rules,)*
                }
            }
        }

        impl ::core::fmt::Display for Locale {
            fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {
                f.write_str(self.as_str())
            }
        }

        impl ::core::str::FromStr for Locale {
            type Err = ::codon::UnknownLocale;

            /// Parses a locale code, ignoring ASCII case.
            fn from_str(s: &str) -> ::core::result::Result<Self, Self::Err> {
                match s {
                    #(#codes2 => Ok(Self::#all),)*
                    _ => Self::ALL
                        .into_iter()
                        .find(|l| l.as_str().eq_ignore_ascii_case(s))
                        .ok_or_else(|| ::codon::UnknownLocale::new(s)),
                }
            }
        }

        ::codon::__impl_serde!(Locale);
    }
}

/// A module of the generated tree.
struct Module {
    key: Vec<String>,
    children: Vec<Child>,
}

enum Child {
    Module(Name, Module),
    Item(usize),
}

fn tree(model: &Model) -> Module {
    let mut root = Module {
        key: Vec::new(),
        children: Vec::new(),
    };
    for (index, item) in model.items.iter().enumerate() {
        let mut node = &mut root;
        for segment in &item.path[..item.path.len() - 1] {
            let name = model::module_ident(segment);
            let position = node
                .children
                .iter()
                .position(|c| matches!(c, Child::Module(n, _) if *n == name));
            let position = position.unwrap_or_else(|| {
                let mut key = node.key.clone();
                key.push(segment.clone());
                node.children.push(Child::Module(
                    name,
                    Module {
                        key,
                        children: Vec::new(),
                    },
                ));
                node.children.len() - 1
            });
            let Child::Module(_, child) = &mut node.children[position] else {
                unreachable!()
            };
            node = child;
        }
        node.children.push(Child::Item(index));
    }
    root
}

fn module(model: &Model, node: &Module, name: &Name, doc: &TokenStream) -> TokenStream {
    let ident = name.ident();
    let children = node.children.iter().map(|child| match child {
        Child::Module(name, child) => {
            let doc = doc_lines(&[format!("Translations under `{}`.", child.key.join("."))]);
            module(model, child, name, &doc)
        }
        Child::Item(index) => function(model, &model.items[*index]),
    });
    let allow = node.key.is_empty().then(allow);
    quote! {
        #doc
        #allow
        pub mod #ident {
            use super::Locale;

            #(#children)*
        }
    }
}

/// One line of preview text for docs.
fn preview(text: &str) -> String {
    const MAX: usize = 100;
    let flat: String = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let flat = flat.replace("```", "'''");
    if flat.chars().count() > MAX {
        let cut: String = flat.chars().take(MAX).collect();
        format!("{cut}…")
    } else {
        flat
    }
}

fn function_doc(model: &Model, item: &Item) -> TokenStream {
    let mut lines = vec![
        format!("`{}`", item.dotted()),
        String::new(),
        "```text".to_owned(),
    ];
    for ((locale, value), fallback) in model.locales.iter().zip(&item.values).zip(&item.fallback) {
        if *fallback {
            lines.push(format!(
                "{}: (missing, uses {})",
                locale.code, model.locales[0].code
            ));
            continue;
        }
        match value {
            Value::Text(text) => lines.push(format!("{}: {}", locale.code, preview(text))),
            Value::List(items) => {
                lines.push(format!(
                    "{}: [{}]",
                    locale.code,
                    preview(&items.join(" | "))
                ));
            }
            Value::Plural(forms) => {
                for (category, text) in forms {
                    lines.push(format!("{}.{category}: {}", locale.code, preview(text)));
                }
            }
        }
    }
    lines.push("```".to_owned());
    doc_lines(&lines)
}

fn function(model: &Model, item: &Item) -> TokenStream {
    let doc = function_doc(model, item);
    let name = item.name.ident();
    let arg_type = if item.html {
        quote!(impl ::codon::HtmlArg)
    } else {
        quote!(impl ::core::fmt::Display)
    };
    let count = (item.kind == Kind::Plural).then(|| quote!(count: i64,));
    let params = item.params.iter().map(|p| {
        let p = format_ident!("{}", model::param_ident(p));
        quote!(#p: #arg_type,)
    });
    let ret = match (item.kind, item.html, item.interpolated()) {
        (Kind::List, false, _) => quote!(&'static [&'static str]),
        (Kind::List, true, _) => quote!(&'static [::codon::Html]),
        (_, true, _) => quote!(::codon::Html),
        (_, false, true) => quote!(String),
        (_, false, false) => quote!(&'static str),
    };
    let arms = model
        .locales
        .iter()
        .zip(&item.values)
        .map(|(locale, value)| {
            let v = variant(locale);
            let expr = value_expr(item, locale, value);
            quote!(Locale::#v => #expr,)
        });
    quote! {
        #doc
        pub fn #name(locale: Locale, #count #(#params)*) -> #ret {
            match locale {
                #(#arms)*
            }
        }
    }
}

fn value_expr(item: &Item, locale: &LocaleInfo, value: &Value) -> TokenStream {
    let interpolated = item.interpolated();
    match value {
        Value::Text(text) => text_expr(text, item.html, interpolated),
        Value::List(items) => {
            if item.html {
                let items = items.iter().map(|s| str_lit(s));
                quote!({
                    const ITEMS: &[::codon::Html] = &[#(::codon::Html::from_static(#items)),*];
                    ITEMS
                })
            } else {
                let items = items.iter().map(|s| str_lit(s));
                quote!(&[#(#items),*])
            }
        }
        Value::Plural(forms) => {
            let form = |c: Category| forms.iter().find(|(f, _)| *f == c).map(|(_, t)| t);
            let other = text_expr(form(Category::Other).expect("checked"), item.html, true);
            if forms
                .iter()
                .all(|(c, _)| *c == Category::Other || !locale.rule.categories().contains(c))
                && form(Category::Zero).is_none()
            {
                return other;
            }
            // Like Rails, an explicit `zero` form is used for 0 in every language.
            let zero = form(Category::Zero).map(|text| {
                let expr = text_expr(text, item.html, true);
                quote!(_ if count == 0 => #expr,)
            });
            let reachable = locale.rule.categories();
            let arms = forms
                .iter()
                .filter(|(c, _)| *c != Category::Other && reachable.contains(c))
                .map(|(c, text)| {
                    let category = format_ident!("{}", format!("{c:?}"));
                    let expr = text_expr(text, item.html, true);
                    quote!(::codon::plural::Category::#category => #expr,)
                });
            let rule = format_ident!("{}", format!("{:?}", locale.rule));
            quote! {
                match ::codon::plural::PluralRule::#rule.category(count) {
                    #zero
                    #(#arms)*
                    _ => #other,
                }
            }
        }
    }
}

/// The expression for one string: `&'static str`, `String` or `Html`
/// depending on `html` and `interpolated`.
fn text_expr(text: &str, html: bool, interpolated: bool) -> TokenStream {
    if !interpolated {
        let lit = str_lit(text);
        return if html {
            quote!(::codon::Html::from_static(#lit))
        } else {
            quote!(#lit)
        };
    }
    let segments = template::parse(text, true);
    let has_args = segments.iter().any(|s| matches!(s, Segment::Arg(_)));
    if !has_args {
        let unescaped: String = segments
            .into_iter()
            .map(|s| match s {
                Segment::Text(t) => t,
                Segment::Arg(_) => unreachable!(),
            })
            .collect();
        let lit = str_lit(&unescaped);
        return if html {
            quote!(::codon::Html::from_static(#lit))
        } else {
            quote!(String::from(#lit))
        };
    }
    if html {
        let capacity = Literal::usize_unsuffixed(text.len() + 32);
        let pushes = segments.iter().map(|s| match s {
            Segment::Text(t) => {
                let lit = str_lit(t);
                quote!(html.push_str(#lit);)
            }
            Segment::Arg(name) => {
                let arg = format_ident!("{}", model::param_ident(name));
                quote!(::codon::HtmlArg::push_html(&#arg, &mut html);)
            }
        });
        quote!({
            let mut html = String::with_capacity(#capacity);
            #(#pushes)*
            ::codon::Html::from_trusted(html)
        })
    } else {
        let mut format = String::new();
        for segment in &segments {
            match segment {
                Segment::Text(t) => format.push_str(&t.replace('{', "{{").replace('}', "}}")),
                Segment::Arg(name) => {
                    format.push('{');
                    format.push_str(&model::param_ident(name));
                    format.push('}');
                }
            }
        }
        let lit = str_lit(&format);
        quote!(format!(#lit))
    }
}

fn lookup(model: &Model) -> TokenStream {
    let allow = allow();
    let module = model.module.ident();
    let arms: Vec<TokenStream> = model
        .items
        .iter()
        .filter(|item| item.kind == Kind::Text && !item.html && !item.interpolated())
        .map(|item| {
            let key = str_lit(&item.dotted());
            let modules = item.path[..item.path.len() - 1]
                .iter()
                .map(|k| model::module_ident(k).ident());
            let name = item.name.ident();
            quote!(#key => self::#module::#(#modules::)*#name(locale),)
        })
        .collect();
    let body = if arms.is_empty() {
        quote!(None)
    } else {
        quote! {
            Some(match key {
                #(#arms)*
                _ => return None,
            })
        }
    };
    quote! {
        /// Looks up a plain translation (no placeholders, plurals, lists or
        /// `_html`) by its dotted key, for keys only known at runtime.
        #allow
        pub fn lookup(locale: Locale, key: &str) -> Option<&'static str> {
            #body
        }
    }
}
